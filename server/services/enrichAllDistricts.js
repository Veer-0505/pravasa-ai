let added = 0;
let updated = 0;
let rejected = 0;

newDistrictPlaces.forEach(p => {
  const isInside = p.lat >= KARNATAKA_BOUNDS.south &&
                   p.lat <= KARNATAKA_BOUNDS.north &&
                   p.lng >= KARNATAKA_BOUNDS.west &&
                   p.lng <= KARNATAKA_BOUNDS.east;
  if (!isInside) {
    console.error(`REJECTED ${p.id}: Out of bounds (${p.lat}, ${p.lng})`);
    rejected++;
    return;
  }

  if (placeMap.has(p.id)) {
    updated++;
    placeMap.set(p.id, { ...placeMap.get(p.id), ...p });
  } else {
    added++;
    placeMap.set(p.id, p);
  }
});

const finalPlaces = Array.from(placeMap.values());
fs.writeFileSync(placesPath, JSON.stringify(finalPlaces, null, 2), 'utf8');

console.log(`Finished enrichment: Added ${added}, Updated ${updated}, Rejected ${rejected}. Total Places: ${finalPlaces.length}`);
